const getStoredLanguage = (): Language => {
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (stored && (stored === 'ru' || stored === 'en' || stored === 'ja')) {
      return stored as Language;
    }
  } catch (error) {
    console.warn('Error reading stored language:', error);
  }
  
  // Detect browser/system language
  try {
    // Try navigator.language first (browser language)
    const browserLang = navigator.language?.split('-')[0]?.toLowerCase();
    if (browserLang === 'ru' || browserLang === 'ja') {
      return browserLang as Language;
    }
    
    // Try navigator.languages (user's preferred languages)
    if (navigator.languages && navigator.languages.length > 0) {
      for (const lang of navigator.languages) {
        const langCode = lang.split('-')[0]?.toLowerCase();
        if (langCode === 'ru' || langCode === 'ja') {
          return langCode as Language;
        }
      }
    }
  } catch (error) {
    console.warn('Error detecting browser language:', error);
  }
  
  return 'en'; // Default to English
};

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  // Initialize language state - use lazy initialization to avoid issues during SSR/hot reload
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      return getStoredLanguage();
    } catch (error) {
      console.warn('Error getting stored language, defaulting to English:', error);
      return 'en';
    }
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    } catch (error) {
      console.warn('Error saving language to localStorage:', error);
    }
  };

  const t = (key: string): string => {
    try {
      return translations[language]?.[key] || translations['en']?.[key] || key;
    } catch (error) {
      console.warn('Error translating key:', key, error);
      return key;
    }
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === null) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
